// Writes src/api/limits.ts from src/api/openapi.json: the limits and enums of
// the API, as values for the forms. schema.d.ts has the types only.
import { readFile, writeFile } from 'node:fs/promises'

const spec = JSON.parse(await readFile(new URL('../src/api/openapi.json', import.meta.url), 'utf8'))
const keys = ['minimum', 'maximum', 'minLength', 'maxLength', 'pattern', 'minItems', 'maxItems', 'enum', 'default']

const schemas = {}
for (const [name, schema] of Object.entries(spec.components.schemas)) {
  const fields = limitsOf(Object.entries(schema.properties ?? {}))
  if (fields) schemas[name] = fields
}

const params = {}
for (const [path, operations] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(operations)) {
    const query = (operation.parameters ?? []).filter((param) => param.in === 'query')
    const fields = limitsOf(query.map((param) => [param.name, param.schema ?? {}]))
    if (fields) params[`${method} ${path}`] = fields
  }
}

await writeFile(
  new URL('../src/api/limits.ts', import.meta.url),
  `// Generated by scripts/gen-limits.mjs from openapi.json. Run pnpm gen:api; do not edit.

/** The limits, enums, and defaults of the fields of each API schema. */
export const limits = ${format(schemas)} as const

/** The limits, enums, and defaults of the query parameters of each operation, as "get /api/jobs". */
export const queryLimits = ${format(params)} as const
`,
)

/** JSON with two-space indents and each list of values on one line. */
function format(value) {
  return JSON.stringify(value, null, 2).replace(/\[\s+([^[\]{}]*?)\s+\]/g, (_, items) => `[${items.split(/,\s+/).join(', ')}]`)
}

/** The fields that have a limit, with only their limits; undefined if none has one. */
function limitsOf(fields) {
  const out = {}
  for (const [name, schema] of fields) {
    const field = pick(schema)
    const items = pick(schema.items ?? {})
    if (Object.keys(items).length > 0) field.items = items
    if (Object.keys(field).length > 0) out[name] = field
  }
  return Object.keys(out).length > 0 ? out : undefined
}

function pick(schema) {
  return Object.fromEntries(keys.filter((key) => key in schema).map((key) => [key, schema[key]]))
}
